#!/usr/bin/env python3
"""Bakes a TrueType font into App/FontAtlas.h for the config app.

The 360 app has no font loading of its own, so the glyphs ship inside the
executable: a 4-bit coverage atlas plus per-glyph metrics. A 4x4 solid block
is reserved at the top-left so rectangles can be drawn with the same shader.

Usage:  python gen_font.py [path/to/font.ttf] [pixel_size]
Default font is DejaVu Sans (free licence, see DejaVu's LICENSE).
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
SIZE = int(sys.argv[2]) if len(sys.argv) > 2 else 28
OUT = sys.argv[3] if len(sys.argv) > 3 else "FontAtlas.h"
ATLAS_W = 512
PAD = 2
FIRST, LAST = 32, 126

font = ImageFont.truetype(FONT, SIZE)
ascent, descent = font.getmetrics()
line_height = ascent + descent

glyphs = []
for c in range(FIRST, LAST + 1):
    ch = chr(c)
    l, t, r, b = font.getbbox(ch)          # relative to the pen at the ascender line
    w, h = max(r - l, 0), max(b - t, 0)
    adv = font.getlength(ch)
    glyphs.append(dict(c=c, l=l, t=t, w=w, h=h, adv=adv))

# Shelf packing; the white block takes the first slot.
x, y, shelf = 4 + PAD, 0, 4
for g in glyphs:
    if x + g["w"] + PAD > ATLAS_W:
        x, y, shelf = 0, y + shelf + PAD, 0
    g["x"], g["y"] = x, y
    x += g["w"] + PAD
    shelf = max(shelf, g["h"])
height = y + shelf + PAD
atlas_h = 1
while atlas_h < height:
    atlas_h *= 2

img = Image.new("L", (ATLAS_W, atlas_h), 0)
draw = ImageDraw.Draw(img)
draw.rectangle([0, 0, 3, 3], fill=255)
for g in glyphs:
    if g["w"] and g["h"]:
        draw.text((g["x"] - g["l"], g["y"] - g["t"]), chr(g["c"]), font=font, fill=255)

px = img.load()
packed = bytearray()
for yy in range(atlas_h):
    for xx in range(0, ATLAS_W, 2):
        hi = (px[xx, yy] + 8) // 17
        lo = (px[xx + 1, yy] + 8) // 17
        packed.append((min(hi, 15) << 4) | min(lo, 15))

with open(OUT, "w", newline="\n") as f:
    f.write("// Generated by tools/gen_font.py - do not edit by hand.\n")
    f.write(f"// Font: {FONT.split('/')[-1]} at {SIZE}px. 4-bit coverage, two texels per byte (high nibble first).\n")
    f.write("#pragma once\n\n")
    f.write(f"#define FONT_ATLAS_W {ATLAS_W}\n#define FONT_ATLAS_H {atlas_h}\n")
    f.write(f"#define FONT_LINE_HEIGHT {line_height}\n#define FONT_ASCENT {ascent}\n")
    f.write(f"#define FONT_FIRST_CHAR {FIRST}\n#define FONT_LAST_CHAR {LAST}\n\n")
    f.write("struct FontGlyph { short x, y, w, h, offX, offY; float advance; };\n\n")
    f.write("static const FontGlyph g_FontGlyphs[] = {\n")
    for g in glyphs:
        name = chr(g["c"]).replace("\\", "backslash")
        f.write(f"    {{ {g['x']}, {g['y']}, {g['w']}, {g['h']}, {g['l']}, {g['t']}, {g['adv']:.2f}f }}, // {g['c']} {name!r}\n")
    f.write("};\n\n")
    f.write(f"static const unsigned char g_FontAtlas4bpp[{len(packed)}] = {{\n")
    for i in range(0, len(packed), 24):
        f.write("    " + ",".join(f"0x{b:02X}" for b in packed[i:i + 24]) + ",\n")
    f.write("};\n")

img.save(OUT.rsplit(".", 1)[0] + "_preview.png")
print(f"{OUT}: atlas {ATLAS_W}x{atlas_h}, line height {line_height}, {len(packed)} bytes")
